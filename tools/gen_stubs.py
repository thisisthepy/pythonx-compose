"""Generate `pythonx.compose` stubs from the binder's Kotlin-named stubs, by the runtime's own rule.

    python3 tools/gen_stubs.py <kotlin-stubs.zip | kotlin-stub-root> [--out pythonx/compose/..]

The input is what python-multiplatform's `PythonStubsTask` writes, either as its CI artefact
`kotlin-stubs` (a zip, read in place) or unpacked: one `androidx/compose/.../__init__.pyi` per Kotlin
package, Kotlin names unchanged. For each module in `pythonx-map.toml`, this reads the stub of the
Kotlin package it maps to and writes the Pythonic one next to the module's `__init__.py`:

- a module function or constant is renamed with `pythonx.compose._reexport.python_name`, the
  function the runtime resolves names with, so an editor completes what the interpreter answers;
- a parameter is renamed with `snake_case`, except the positional-only `receiver` and anonymous
  `__aN` slots, which a caller never writes by name; keyword-only markers stay;
- a function whose explicit overload set is named like a class of the same stub (a constructor-shaped
  `DpRect__Dp_Dp_Dp_Dp` beside `class DpRect`) gets no base name: the class and its `__init__` are that name;
- the binder's own `@overload` sets are kept in its order (with its `# type: ignore` comments). An
  input with explicit overloads only (`padding__Dp`, the first upstream format) also gets
  `@overload`s of the base name, fewest parameters first because a type checker takes the first
  match;
- a stub class keeps its name. Its members are renamed with `python_name`, which is the binder's
  member-resolver rule, and the parameters of a member's callable protocol are snake_case like a
  module function's, because the resolver also translates a method's keywords (the receiver and
  anonymous slots keep their names). The stubs are Pythonic-only: a method's Kotlin keyword still
  works at run time and is a type error here. A static method (a function of a Kotlin object) is
  reached through `KotlinObject`, so its parameters are snake_case too;
- a Kotlin object served as a sub-package (`Alignment`) becomes a class in its parent module's stub,
  whether the input has it as `<Object>/__init__.pyi` or already as a class in the parent stub
  (python-multiplatform #44). A sub-package directory holding only `__init__.pyi` would be a
  namespace package at run time and shadow the `KotlinObject` the re-export rule serves. An object
  whose name the parent uses for a function is left out: at run time that name is the function;
- a property keeps its decorators in step with its name (`@layout_direction.setter`); an object's
  nested Kotlin types (`class Horizontal` in `Alignment`'s stub, `End: Horizontal`) become classes of
  its class, referenced as `Alignment.Horizontal` (from another module `pythonx.compose.ui.Alignment.Horizontal`),
  except a type derived from exactly one other nested type, which is `Any` (see `_Qualify`); an object's
  explicit overload set (`spacedBy__Dp`) also gets its base name, as a static method;
- an object's constants are also grouped by the type nested in it that their docstring declares
  them as (`Alignment.End(): Alignment.Horizontal`), as a class nested in the object's class
  (`Alignment.Horizontal.End`), the runtime's `ConstantGroup` rule; a member of that name wins, unless
  it is the nested Kotlin type itself, which then is the group;
- a reference to another Kotlin package names the `pythonx.compose` module the manifest lists first
  for it, and its import is rewritten to match; a package the manifest does not map, or a name the
  target stub does not declare as a class, becomes `typing.Any`;
- a module that maps a Kotlin package an earlier module already maps re-exports that module, and
  the manifest's `[aliases]` are re-exported, because at run time those names are the same objects
  (a name lent under another one, through an attribute path, is assigned that path of the source's stub);
- names the module's own `__init__.py` defines (`runtime.Composable`) are carried over, because a
  `.pyi` beside a module replaces everything a type checker knows about it; so is a bare
  annotation (`app_root: State`), the way a module declares a name its `__getattr__` creates.

Nothing here names a Kotlin declaration; it is the same rule `_reexport.py` applies at run time.
The output is deterministic: the same input regenerates the same text.
"""

