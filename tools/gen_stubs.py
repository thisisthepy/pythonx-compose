def _docstring(text: str) -> str:
    if '"""' in text or "\\" in text or text.endswith('"'):
        return repr(text)
    return f'"""{text}"""'


def _parameter(argument: ast.arg, default: ast.expr | None) -> str:
    text = argument.arg
    if argument.annotation is not None:
        text += f": {ast.unparse(argument.annotation)}"
        if default is not None:
            text += f" = {ast.unparse(default)}"
    elif default is not None:
        text += f"={ast.unparse(default)}"
    return text


def _parameters(arguments: ast.arguments) -> str:
    positional = arguments.posonlyargs + arguments.args
    defaults = [None] * (len(positional) - len(arguments.defaults)) + list(arguments.defaults)
    parts = [_parameter(a, d) for a, d in zip(positional, defaults)]
    if arguments.posonlyargs:
        parts.insert(len(arguments.posonlyargs), "/")
    if arguments.vararg is not None:
        parts.append("*" + _parameter(arguments.vararg, None))
    elif arguments.kwonlyargs:
        parts.append("*")
    parts.extend(_parameter(a, d) for a, d in zip(arguments.kwonlyargs, arguments.kw_defaults))
    if arguments.kwarg is not None:
        parts.append("**" + _parameter(arguments.kwarg, None))
    return ", ".join(parts)


def _ignore(node: ast.AST) -> str:
    tag = getattr(node, "type_ignore", None)
    return f"  # type: ignore{tag}" if tag is not None else ""


def _emit(node: ast.stmt, indent: str = "") -> list[str]:
    if isinstance(node, ast.FunctionDef):
        lines = [f"{indent}@{ast.unparse(d)}" for d in node.decorator_list]
        head = f"{indent}def {node.name}({_parameters(node.args)})"
        if node.returns is not None:
            head += f" -> {ast.unparse(node.returns)}"
        head += ":"
        doc = ast.get_docstring(node, clean=False)
        if doc is None:
            lines.append(f"{head} ...{_ignore(node)}")
        else:
            lines += [f"{head}{_ignore(node)}", f"{indent}    {_docstring(doc)}", f"{indent}    ..."]
        return lines
    if isinstance(node, ast.ClassDef):
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        lines = [f"{indent}class {node.name}({bases}):" if bases else f"{indent}class {node.name}:"]
        for member in node.body:
            lines += _emit(member, indent + "    ")
        if len(lines) == 1:
            lines.append(f"{indent}    ...")
        return lines
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
        return [f"{indent}{_docstring(node.value.value)}"]
    return [f"{indent}{ast.unparse(node)}{_ignore(node)}"]


def _emit_module(body: list[ast.stmt]) -> str:
    out: list[str] = []
    previous: ast.stmt | None = None
    for node in body:
        attached = previous is not None and (
            (isinstance(node, ast.Expr) and isinstance(previous, ast.AnnAssign))
            or (isinstance(node, ast.FunctionDef) and isinstance(previous, ast.FunctionDef)
                and _is_overload(node) and _is_overload(previous) and node.name == previous.name)
        )
        if previous is not None and not attached:
            out.append("")
        out.extend(_emit(node))
        previous = node
    return "\n".join(out) + "\n" if out else ""


def own_definitions(init_py: Path) -> list[str]:
    """Stub text for the public functions and classes a package's own `__init__.py` defines."""
    if not init_py.is_file():
        return []
    stubs = []
    for node in ast.parse(init_py.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            node.body = [ast.Expr(ast.Constant(...))]
            node.decorator_list = []
            stubs.append(ast.unparse(node) + "\n")
        elif (
            isinstance(node, ast.AnnAssign)
            and node.value is None
            and isinstance(node.target, ast.Name)
            and not node.target.id.startswith("_")
        ):
            # A name the module answers through its own `__getattr__` (`runtime.app_root`).
            stubs.append(ast.unparse(node) + "\n")
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            stubs.append(f"class {node.name}: ...\n")
    return stubs


def generate(kotlin_stubs: Path, package_root: Path, notes: list[str] | None = None) -> dict[Path, str]:
    """Every stub this manifest yields: output path -> text. Writes nothing.

    [kotlin_stubs] is the artefact zip or a directory; what had to be left out is appended to [notes].
    """
    stubs = KotlinStubs(kotlin_stubs)
    converter = Converter(stubs)
    out: dict[Path, str] = {}
    for module_name, kotlin_package in manifest()["modules"].items():
        module_dir = package_root.joinpath(*module_name.split(".")[1:])
        first = converter.first_module[kotlin_package]
        source = stubs.stub(kotlin_package)
        if first != module_name:
            # The same Kotlin package under a second name: at run time, the same objects.
            text = header(stubs.provenance) + f"from {first} import *\n"
        elif source is not None:
            text = converter.convert(source, kotlin_package, module_name)
        else:
            text = header(stubs.provenance)
        own = own_definitions(module_dir / "__init__.py")
        if own:
            text += "\n" + "\n".join(own)
        out[module_dir / STUB_NAME] = text
    if notes is not None:
        notes.extend(converter.notes)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("kotlin_stubs", type=Path, help="the `kotlin-stubs` zip, or a directory of Kotlin-named stubs")
    parser.add_argument("--out", type=Path, default=REPO / "pythonx")
    args = parser.parse_args(argv)
    if not args.kotlin_stubs.exists():
        parser.error(f"{args.kotlin_stubs} does not exist")
    notes: list[str] = []
    for path, text in generate(args.kotlin_stubs, args.out, notes).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path)
    for note in notes:
        print(f"left out: {note}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
